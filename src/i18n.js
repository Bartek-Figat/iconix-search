/** Strings for a locale ('pl-PL' -> pl), merged over English, plus user overrides. */
export function getStrings(locale = 'en', overrides = null) {
  const lang = String(locale || 'en').toLowerCase().split(/[-_]/)[0];
  return { ...STRINGS.en, ...(STRINGS[lang] || {}), ...(overrides || {}) };
}
